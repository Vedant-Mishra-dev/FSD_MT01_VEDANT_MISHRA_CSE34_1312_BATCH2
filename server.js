'use strict';

const express = require('express');

const PORT = Number(process.env.PORT) || 3000;

// The assignment requires all records to remain in server memory.
// These are the three initial products supplied in Set C.
const INITIAL_PRODUCTS = [
  {
    id: 301,
    name: 'Wireless Mouse',
    category: 'Electronics',
    price: 799,
    quantity: 25,
    inStock: true
  },
  {
    id: 302,
    name: 'Notebook',
    category: 'Stationery',
    price: 60,
    quantity: 100,
    inStock: true
  },
  {
    id: 303,
    name: 'USB Keyboard',
    category: 'Electronics',
    price: 999,
    quantity: 0,
    inStock: false
  }
];

const PRODUCT_FIELDS = ['name', 'category', 'price', 'quantity', 'inStock'];

/**
 * Validate the editable fields of a product.
 * IDs are generated by the application and must not be supplied by clients.
 *
 * @param {unknown} body
 * @returns {string[]} A list of validation errors; an empty list means valid.
 */
function validateProduct(body) {
  if (body === null || typeof body !== 'object' || Array.isArray(body)) {
    return ['Request body must be a JSON object.'];
  }

  const errors = [];
  const allowedFields = new Set(PRODUCT_FIELDS);

  for (const field of Object.keys(body)) {
    if (!allowedFields.has(field)) {
      errors.push(`Unexpected field: ${field}.`);
    }
  }

  for (const field of PRODUCT_FIELDS) {
    if (!Object.prototype.hasOwnProperty.call(body, field)) {
      errors.push(`${field} is required.`);
    }
  }

  if (typeof body.name !== 'string' || body.name.trim().length === 0) {
    errors.push('name must be a non-empty string.');
  }

  if (typeof body.category !== 'string' || body.category.trim().length === 0) {
    errors.push('category must be a non-empty string.');
  }

  if (typeof body.price !== 'number' || !Number.isFinite(body.price) || body.price < 0) {
    errors.push('price must be a non-negative number.');
  }

  if (
    typeof body.quantity !== 'number' ||
    !Number.isSafeInteger(body.quantity) ||
    body.quantity < 0
  ) {
    errors.push('quantity must be a non-negative integer.');
  }

  if (typeof body.inStock !== 'boolean') {
    errors.push('inStock must be a Boolean value (true or false).');
  }

  return errors;
}

/**
 * Return a new object containing only the fields accepted from a client.
 * This prevents clients from changing an existing product's ID.
 *
 * @param {object} body
 * @returns {{name: string, category: string, price: number, quantity: number, inStock: boolean}}
 */
function getProductFields(body) {
  return {
    name: body.name.trim(),
    category: body.category.trim(),
    price: body.price,
    quantity: body.quantity,
    inStock: body.inStock
  };
}

/**
 * Parse a route ID without accepting decimals, zero, negative values or text.
 *
 * @param {string} value
 * @returns {number|null}
 */
function parseProductId(value) {
  if (!/^\d+$/.test(value)) {
    return null;
  }

  const id = Number(value);
  return Number.isSafeInteger(id) && id > 0 ? id : null;
}

/**
 * Create the Express application. Keeping this separate from app.listen()
 * allows the API to be tested on a temporary port without starting port 3000.
 *
 * @param {{initialProducts?: Array<object>}} [options]
 * @returns {import('express').Express}
 */
function createApp(options = {}) {
  const seedProducts = options.initialProducts || INITIAL_PRODUCTS;
  const products = seedProducts.map((product) => ({ ...product }));
  let nextId = products.length > 0
    ? Math.max(...products.map((product) => product.id)) + 1
    : 1;

  const app = express();

  app.disable('x-powered-by');
  app.use(express.json({ limit: '10kb' }));

  // 1. GET /api/products - return every product.
  app.get('/api/products', (req, res) => {
    return res.status(200).json(products);
  });

  // 2. POST /api/products - validate and create a product.
  app.post('/api/products', (req, res) => {
    const errors = validateProduct(req.body);

    if (errors.length > 0) {
      return res.status(400).json({
        message: 'Invalid product data.',
        errors
      });
    }

    const newProduct = {
      id: nextId,
      ...getProductFields(req.body)
    };
    nextId += 1;
    products.push(newProduct);

    return res.status(201).json({
      message: 'Product created successfully.',
      product: newProduct
    });
  });

  // 6. GET /api/products/filter?category=value
  // This route must appear before /api/products/:id so "filter" is not
  // interpreted as an ID.
  app.get('/api/products/filter', (req, res) => {
    const { category } = req.query;

    if (typeof category !== 'string' || category.trim().length === 0) {
      return res.status(400).json({
        message: 'Please provide a non-empty category query parameter.'
      });
    }

    const normalizedCategory = category.trim().toLowerCase();
    const matchingProducts = products.filter(
      (product) => product.category.toLowerCase() === normalizedCategory
    );

    return res.status(200).json(matchingProducts);
  });

  // 3. GET /api/products/:id - return one product.
  app.get('/api/products/:id', (req, res) => {
    const id = parseProductId(req.params.id);

    if (id === null) {
      return res.status(400).json({ message: 'Product ID must be a positive integer.' });
    }

    const product = products.find((item) => item.id === id);

    if (!product) {
      return res.status(404).json({ message: 'Product not found.' });
    }

    return res.status(200).json(product);
  });

  // 4. PUT /api/products/:id - replace all editable fields of one product.
  app.put('/api/products/:id', (req, res) => {
    const id = parseProductId(req.params.id);

    if (id === null) {
      return res.status(400).json({ message: 'Product ID must be a positive integer.' });
    }

    const productIndex = products.findIndex((item) => item.id === id);

    if (productIndex === -1) {
      return res.status(404).json({ message: 'Product not found.' });
    }

    const errors = validateProduct(req.body);

    if (errors.length > 0) {
      return res.status(400).json({
        message: 'Invalid product data.',
        errors
      });
    }

    const updatedProduct = {
      id,
      ...getProductFields(req.body)
    };
    products[productIndex] = updatedProduct;

    return res.status(200).json({
      message: 'Product updated successfully.',
      product: updatedProduct
    });
  });

  // 5. DELETE /api/products/:id - remove one product.
  app.delete('/api/products/:id', (req, res) => {
    const id = parseProductId(req.params.id);

    if (id === null) {
      return res.status(400).json({ message: 'Product ID must be a positive integer.' });
    }

    const productIndex = products.findIndex((item) => item.id === id);

    if (productIndex === -1) {
      return res.status(404).json({ message: 'Product not found.' });
    }

    const [deletedProduct] = products.splice(productIndex, 1);

    return res.status(200).json({
      message: 'Product deleted successfully.',
      product: deletedProduct
    });
  });

  // Consistent JSON response for an unknown route.
  app.use((req, res) => {
    return res.status(404).json({ message: 'Route not found.' });
  });

  // Handle malformed JSON and other Express errors in a predictable way.
  // Error-handling middleware has four parameters by design.
  app.use((err, req, res, next) => {
    if (err instanceof SyntaxError && err.status === 400 && 'body' in err) {
      return res.status(400).json({ message: 'Invalid JSON request body.' });
    }

    if (err.type === 'entity.too.large') {
      return res.status(413).json({ message: 'Request body is too large.' });
    }

    console.error(err);
    return res.status(500).json({ message: 'Internal server error.' });
  });

  return app;
}

// Start the server only when this file is run directly with `node server.js`.
if (require.main === module) {
  const app = createApp();
  app.listen(PORT, () => {
    console.log(`Product Inventory API is running at http://localhost:${PORT}`);
    console.log('Press Ctrl+C to stop the server.');
  });
}

module.exports = {
  createApp,
  INITIAL_PRODUCTS,
  validateProduct,
  parseProductId
};
